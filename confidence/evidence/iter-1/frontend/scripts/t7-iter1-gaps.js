// Iteration-1 gap checks that have no iteration-0 counterpart: G-1-12 (focus and summary on an invalid submit), G-1-13 ('View in
// feed' for other types and tenants), plus the reference screenshots per tab and theme.
const L = require('./lib')
const { record, api, publishBody, newPage, setTenant, field, form, UI } = L
L.setFile('t7-iter1-gaps')
const RUN = Date.now().toString(36)
const T = (n) => `fe1-${n}-${RUN}`
const activeInfo = (page) => page.evaluate(() => { const e = document.activeElement; if (!e) return null; const r = e.getBoundingClientRect(); return { tag: e.tagName.toLowerCase(), id: e.id || null, role: e.getAttribute('role'), checked: e.getAttribute('aria-checked'), text: (e.textContent || '').trim().slice(0, 30), inViewport: r.top >= 0 && r.bottom <= window.innerHeight && r.height > 0, top: Math.round(r.top), innerHeight: window.innerHeight, scrollY: Math.round(window.scrollY) } })
const summary = (page) => page.locator('[role="alert"]').filter({ has: page.locator('button') })

;(async () => {
  const browser = await L.launch()
  try {
    // ---------- G-1-12 ----------
    {
      const { context, page } = await newPage(browser, { viewport: { width: 1100, height: 560 } })
      await L.gotoPublish(page, '')
      await page.waitForSelector('form')
      await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
      const scrolled = await page.evaluate(() => Math.round(window.scrollY))
      await field.submit(page).click()
      await page.waitForTimeout(400)
      const a1 = await activeInfo(page)
      const text = (await summary(page).textContent()).trim()
      const buttons = await summary(page).getByRole('button').allTextContents()
      record('F-55', "G-1-12: submitting an empty form from the bottom of the page focuses the first invalid field (Title) and scrolls it into view; the summary says '3 fields need attention:' with one button per field", a1 && /-title$/.test(a1.id || '') && a1.inViewport && /^3 fields need attention:/.test(text) && buttons.length === 3, { scrolledBeforeSubmit: scrolled, focused: a1, summary: text, buttons })
      await summary(page).getByRole('button', { name: /Publisher/ }).click()
      await page.waitForTimeout(300)
      const a2 = await activeInfo(page)
      record('F-55', 'G-1-12: a summary button moves focus to its field (Publisher) and brings it into view', a2 && /-publisher$/.test(a2.id || '') && a2.inViewport, a2)
      await setTenant(page, T('focus'))
      await field.publisher(page).fill('fe-oncall')
      await field.title(page).fill('focus probe')
      await field.severity(page, 'Info').click()
      await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
      await field.submit(page).click()
      await page.waitForTimeout(400)
      const a3 = await activeInfo(page)
      const text3 = (await summary(page).textContent()).trim()
      record('F-55', "G-1-12: when the severity is the only problem, focus lands on the selected segment of the Severity radiogroup; the summary says 'One field needs attention: Severity'", a3 && a3.role === 'radio' && a3.checked === 'true' && a3.text === 'Info' && a3.inViewport && /^One field needs attention:/.test(text3) && /Severity/.test(text3), { focused: a3, summary: text3 })
      await field.severity(page, 'Major').click()
      await field.type(page, 'Maintenance').click()
      await page.evaluate(() => window.scrollTo(0, 0))
      await field.submit(page).click()
      await page.waitForTimeout(400)
      const a4 = await activeInfo(page)
      record('F-55', 'G-1-12: MAINTENANCE without an end → the Timing panel opens and focus lands on the Ends input, scrolled into view', a4 && /-ends$/.test(a4.id || '') && a4.inViewport, a4)
      await field.type(page, 'Change').click()
      await field.ticket(page).fill('inc12')
      await page.evaluate(() => window.scrollTo(0, 0))
      await field.submit(page).click()
      await page.waitForTimeout(400)
      const a5 = await activeInfo(page)
      record('F-55', 'G-1-12: a bad incident number on an otherwise valid CHANGE → focus on the ServiceNow incident input', a5 && /-ticket$/.test(a5.id || '') && a5.inViewport, a5)
      record('F-55', 'G-1-12: nothing was sent while invalid', page.cap.requests.filter((r) => r.method === 'POST').length === 0, `POSTs=${page.cap.requests.filter((r) => r.method === 'POST').length}`)
      await context.close()
    }

    // ---------- G-1-13 ----------
    {
      const { context, page } = await newPage(browser)
      const home = T('home'), other = T('other')
      await L.gotoPublish(page, home)
      await page.waitForSelector('form')
      await field.tenant(page).fill(other)
      await field.type(page, 'Incident').click()
      await field.title(page).fill('incident elsewhere')
      await field.publisher(page).fill('fe-oncall')
      await Promise.all([page.waitForResponse((r) => r.request().method() === 'POST'), field.submit(page).click()])
      await page.waitForSelector('text=Incident published')
      await page.getByRole('button', { name: 'View in feed' }).click()
      await page.waitForSelector('article', { timeout: 10000 })
      await page.waitForTimeout(300)
      const headerTenant = await page.locator('input[aria-label="Tenant"]').inputValue()
      const typeValue = await page.getByRole('combobox', { name: 'Type' }).inputValue()
      const listed = await page.locator('section', { has: page.locator('h2', { hasText: 'Active now' }) }).locator('article h3', { hasText: 'incident elsewhere' }).count()
      const q = page.cap.requests.filter((r) => /\/v1\/feed\?/.test(r.url)).slice(-1)[0]
      record('F-56', "G-1-13: 'View in feed' for an INCIDENT published to another tenant lands on that tenant's feed filtered to Incident, with the notice listed", page.url().endsWith('#/feed') && headerTenant === other && typeValue === 'INCIDENT' && listed === 1, { headerTenant, typeValue, listed, lastFeedQuery: q && new URL(q.url).search })
      await page.goto(UI + '/#/publish')
      await page.waitForSelector('form')
      await field.type(page, 'Maintenance').click()
      await field.title(page).fill('maintenance elsewhere')
      await field.schedule(page).click()
      await field.starts(page).fill(await L.localPlus(page, 24 * 3600000))
      await field.ends(page).fill(await L.localPlus(page, 26 * 3600000))
      await Promise.all([page.waitForResponse((r) => r.request().method() === 'POST'), field.submit(page).click()])
      await page.waitForSelector('text=Maintenance scheduled')
      await page.getByRole('button', { name: 'View in feed' }).click()
      await page.waitForSelector('article h3:has-text("maintenance elsewhere")', { timeout: 10000 })
      const typeM = await page.getByRole('combobox', { name: 'Type' }).inputValue()
      const underUpcoming = await page.locator('section', { has: page.locator('h2', { hasText: 'Upcoming' }) }).locator('article h3', { hasText: 'maintenance elsewhere' }).count()
      record('F-56', "G-1-13: 'View in feed' for a scheduled MAINTENANCE filters to Maintenance and shows it under Upcoming", typeM === 'MAINTENANCE' && underUpcoming === 1, { typeM, underUpcoming })
      await page.goto(UI + '/#/publish')
      await page.waitForSelector('form')
      await field.type(page, 'Change').click()
      await field.severity(page, 'Info').click()
      await field.title(page).fill('change elsewhere')
      await Promise.all([page.waitForResponse((r) => r.request().method() === 'POST'), field.submit(page).click()])
      await page.waitForSelector('text=Change published')
      await page.getByRole('button', { name: 'View in feed' }).click()
      await page.waitForSelector('article h3:has-text("change elsewhere")', { timeout: 10000 })
      const typeC = await page.getByRole('combobox', { name: 'Type' }).inputValue()
      await page.getByRole('combobox', { name: 'Type' }).selectOption('OUTAGE')
      await page.waitForTimeout(600)
      const q2 = page.cap.requests.filter((r) => /\/v1\/feed\?/.test(r.url)).slice(-1)[0]
      record('F-56', "G-1-13: 'View in feed' for a CHANGE filters to Change; the filter can still be changed by hand afterwards", typeC === 'CHANGE' && /type=OUTAGE/.test(q2.url), { typeC, afterManualChange: new URL(q2.url).search })
      await context.close()
    }

    // ---------- reference screenshots ----------
    {
      const tenant = T('shots')
      await api('POST', '/v1/communications', publishBody(tenant, { title: 'Card payments failing for EU customers', severity: 'CRITICAL', affectedServices: ['payments-api', 'checkout-web'], ticket: { number: 'INC0012345', url: 'https://acme.service-now.com/nav_to.do?uri=incident.do?sysparm_query=number=INC0012345' }, audience: 'INTERNAL', endsAt: new Date(Date.now() + 7200000).toISOString(), body: 'Authorisations time out at the acquirer.\nRetries succeed for about one in three attempts.' }))
      await api('POST', '/v1/communications', publishBody(tenant, { title: 'Search latency elevated', type: 'INCIDENT', severity: 'MINOR', affectedServices: ['search-api'] }))
      await api('POST', '/v1/communications', publishBody(tenant, { title: 'Database maintenance window', type: 'MAINTENANCE', severity: 'INFO', affectedServices: ['payments-api'], startsAt: new Date(Date.now() + 86400000).toISOString(), endsAt: new Date(Date.now() + 90000000).toISOString() }))
      for (const scheme of ['light', 'dark']) {
        const { context, page } = await newPage(browser, { colorScheme: scheme })
        await page.goto(UI + '/#/feed')
        await setTenant(page, tenant)
        await page.getByRole('combobox', { name: 'Type' }).selectOption('')
        await page.waitForSelector('article')
        await page.waitForTimeout(600)
        await L.shot(page, `feed-${scheme}`)
        await page.goto(UI + '/#/publish')
        await page.waitForSelector('form')
        await field.schedule(page).click()
        await page.waitForTimeout(200)
        await L.shot(page, `publish-${scheme}`)
        if (scheme === 'light') {
          await setTenant(page, '')
          await field.submit(page).click()
          await page.waitForTimeout(300)
          await L.shot(page, 'publish-errors-light')
          await setTenant(page, tenant)
          await field.title(page).fill('Screenshot outage')
          await field.publisher(page).fill('fe-oncall')
          await Promise.all([page.waitForResponse((r) => r.request().method() === 'POST'), field.submit(page).click()])
          await page.waitForSelector('text=Outage published')
          await page.waitForTimeout(300)
          await L.shot(page, 'publish-done-light')
        }
        record('F-53', `reference screenshots taken (${scheme}); no console/page errors while rendering both tabs`, page.cap.errors.length === 0 && page.cap.console.filter((c) => c.type === 'error').length === 0, { errors: page.cap.errors, console: page.cap.console.slice(0, 5) })
        await context.close()
      }
    }
  } finally {
    await browser.close()
    L.flush()
  }
})().catch((e) => { console.error('SCRIPT ERROR', e); L.flush(); process.exit(1) })
